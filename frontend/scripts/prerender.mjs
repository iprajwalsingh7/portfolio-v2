/**
 * Build-time prerender.
 *
 * content.json + src/styles/index.css -> index.html
 *
 * Vite then treats that index.html as its entry: it hashes and injects the JS
 * bundle and leaves our inlined <style> alone. The CSS is minified with esbuild
 * (already a Vite dependency, so no extra install) before inlining.
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from 'esbuild';
import { renderDocument } from './template.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const repo = resolve(root, '..');

const CONTENT = resolve(root, 'content.json');
const CSS = resolve(root, 'src/styles/index.css');
const OUT = resolve(root, 'index.html');

// The backend serves the same content over /api/content, so it reads the very
// same file. One source of truth, no drift between page and API.
const BACKEND_COPY = resolve(repo, 'backend/src/main/resources/content.json');

async function main() {
  const raw = await readFile(CONTENT, 'utf8');
  const content = JSON.parse(raw);
  const cssSource = await readFile(CSS, 'utf8');

  const { code: css, warnings } = await transform(cssSource, {
    loader: 'css',
    minify: true,
    target: ['chrome111', 'firefox111', 'safari16'],
  });
  for (const w of warnings) console.warn(`[css] ${w.text}`);

  const html = renderDocument({
    content,
    css: css.trim(),
    entry: '/src/main.ts',
  });

  await writeFile(OUT, html, 'utf8');

  // robots.txt and sitemap.xml carry the canonical host, so generate them from
  // the same source rather than leaving two hand-edited files to drift.
  const site = content.meta.siteUrl.replace(/\/$/, '');
  await writeFile(
    resolve(root, 'public/robots.txt'),
    `User-agent: *\nAllow: /\n\nSitemap: ${site}/sitemap.xml\n`,
    'utf8'
  );
  await writeFile(
    resolve(root, 'public/sitemap.xml'),
    `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url>
    <loc>${site}/</loc>
    <changefreq>monthly</changefreq>
    <priority>1.0</priority>
  </url>
</urlset>
`,
    'utf8'
  );

  // _headers reproduces the backend's cache policy for static hosting.
  // Cloudflare Workers static assets and Pages both honour this file; without it
  // the immutable policy on hashed assets only exists when Spring Boot serves
  // them, and a CDN deploy would revalidate every file on every visit.
  await writeFile(
    resolve(root, 'public/_headers'),
    `# Generated by scripts/prerender.mjs — do not edit.
# Mirrors config/CacheHeadersFilter.java so both deployment paths agree.

# Content-hashed by Vite: the filename changes whenever the bytes do.
/assets/*
  Cache-Control: public, max-age=31536000, immutable

# Stable names, immutable content.
/fonts/*
  Cache-Control: public, max-age=31536000, immutable

# Must never be cached: it names the current hashed assets, so caching it would
# make a deploy invisible to anyone who had already visited.
/
  Cache-Control: no-cache, must-revalidate
/index.html
  Cache-Control: no-cache, must-revalidate

# Security headers, matching config/SecurityHeadersFilter.java. A static host has
# no filter chain, so they have to be declared here.
/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()
  Content-Security-Policy: default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; font-src 'self'; connect-src 'self'; form-action 'self'; base-uri 'self'; frame-ancestors 'none'; object-src 'none'
`,
    'utf8'
  );

  // A 404 that looks like the site, rather than the host's default page.
  await writeFile(
    resolve(root, 'public/404.html'),
    `<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Not found — ${content.meta.name}</title>
<meta name="robots" content="noindex">
<style>
  body{margin:0;min-height:100vh;display:grid;place-items:center;background:#0b0b0c;
       color:#efede8;font:400 16px/1.6 system-ui,-apple-system,sans-serif;
       text-align:center;padding:24px}
  h1{font-size:clamp(48px,14vw,140px);letter-spacing:-.05em;margin:0 0 8px;line-height:1}
  p{color:#a3a1a6;margin:0 0 32px}
  a{display:inline-block;background:#c8ff4d;color:#0b0b0c;text-decoration:none;
    padding:14px 26px;border-radius:999px;font-size:12px;letter-spacing:.1em;
    text-transform:uppercase;font-weight:500}
</style></head>
<body><main>
  <h1>404<span style="color:#c8ff4d">.</span></h1>
  <p>That page does not exist.</p>
  <a href="/">Back to the site</a>
</main></body></html>
`,
    'utf8'
  );

  await mkdir(dirname(BACKEND_COPY), { recursive: true });
  await writeFile(BACKEND_COPY, raw, 'utf8');

  const kb = (n) => `${(n / 1024).toFixed(1)} kB`;
  console.log(
    `prerender  index.html ${kb(Buffer.byteLength(html))}  ` +
      `(css ${kb(Buffer.byteLength(css))} inlined, ` +
      `${content.sections.length} sections)`
  );
}

main().catch((err) => {
  console.error('[prerender] failed:', err);
  process.exit(1);
});
